    /**
     * التبديل بين التبويبات
     */
    function switchTab(tabId) {
        const tabs = document.querySelectorAll('.pg-tab-btn');
        const panes = document.querySelectorAll('.pg-pane');

        tabs.forEach(t => {
            if (t.dataset.tab === tabId) {
                t.classList.add('active');
            } else {
                t.classList.remove('active');
            }
        });

        panes.forEach(p => {
            if (p.id === `pg-pane-${tabId}`) {
                p.classList.add('active');
            } else {
                p.classList.remove('active');
            }
        });
    }

    /**
     * فتح وإغلاق كارت الأكورديون
     */
    function toggleCard(cardId) {
        const card = document.getElementById(cardId);
        if (card) {
            card.classList.toggle('expanded');
        }
    }

    /**
     * نسخ نص الدعاء
     */
    function copyDua(encodedText, btnEl) {
        const text = decodeURIComponent(encodedText);
        navigator.clipboard.writeText(text).then(() => {
            if (btnEl) {
                const originalHtml = btnEl.innerHTML;
                btnEl.innerHTML = `<i class="fa-solid fa-check text-green"></i> <span>تم النسخ</span>`;
                btnEl.classList.add('copied');
                setTimeout(() => {
                    btnEl.innerHTML = originalHtml;
                    btnEl.classList.remove('copied');
                }, 2000);
            }
            if (window.showToast) {
                window.showToast("تم نسخ الدعاء المبارك بنجاح 🤲");
            }
        }).catch(() => {
            // Fallback
            const ta = document.createElement("textarea");
            ta.value = text;
            document.body.appendChild(ta);
            ta.select();
            document.execCommand("copy");
            document.body.removeChild(ta);
            if (window.showToast) {
                window.showToast("تم نسخ الدعاء المبارك بنجاح 🤲");
            }
        });
    }

    /**
     * فتح المودال في التطبيق المحمول أو الانتقال للسكشن
     */
    function openPrayerGuideSection() {
        const section = document.getElementById('prayer-guide-section');
        if (section) {
            section.scrollIntoView({ behavior: 'smooth' });
            return;
        }
        // في حال كان مفتوحاً داخل app.html
        if (typeof window.openServiceInApp === "function") {
            window.openServiceInApp('prayer-guide');
        }
    }

