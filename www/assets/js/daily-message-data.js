function getDailyMessageOfTheDay() {
    const now = new Date();
    // الحصول على يوم في السنة (1 - 365)
    const start = new Date(now.getFullYear(), 0, 0);
    const diff = now - start;
    const oneDay = 1000 * 60 * 60 * 24;
    const dayOfYear = Math.floor(diff / oneDay);
    const index = dayOfYear % DAILY_SPIRITUAL_MESSAGES.length;
    return DAILY_SPIRITUAL_MESSAGES[index] || DAILY_SPIRITUAL_MESSAGES[0];
}
